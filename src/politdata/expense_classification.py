EXPENSE_CATEGORY_PATTERNS = tuple(
    (category, re.compile(pattern, re.IGNORECASE))
    for category, pattern in _CATEGORY_PATTERN_TEXT
)


def classify_expense_categories(frame: pd.DataFrame) -> pd.Series:
    """Return one conservative primary category for each expense row."""

    result = pd.Series(
        UNCLASSIFIED_EXPENSE_CATEGORY,
        index=frame.index,
        dtype="string",
        name=EXPENSE_CATEGORY_COLUMN,
    )

    receiver_type = frame.get(
        "receiver_type",
        pd.Series(pd.NA, index=frame.index, dtype="string"),
    ).astype("string")
    internal = receiver_type.eq("internal_party_transfer").fillna(False)
    result.loc[internal] = INTERNAL_TRANSFER_EXPENSE_CATEGORY

    purpose = frame.get(
        "payment_purpose",
        pd.Series(pd.NA, index=frame.index, dtype="string"),
    )
    reason = frame.get(
        "payment_reason",
        pd.Series(pd.NA, index=frame.index, dtype="string"),
    )
    text = (purpose.fillna("").astype(str) + " " + reason.fillna("").astype(str)).map(
        normalize_expense_text
    )

    for category, pattern in EXPENSE_CATEGORY_PATTERNS:
        available = result.eq(UNCLASSIFIED_EXPENSE_CATEGORY) & ~internal
        if not available.any():
            break
        matched = text.str.contains(pattern, na=False)
        result.loc[available & matched] = category

    return result
