EXPENSE_CATEGORY_COLUMN = "expense_category_ai_generated"
UNCLASSIFIED_EXPENSE_CATEGORY = "Не класифіковано"
INTERNAL_TRANSFER_EXPENSE_CATEGORY = "Внутрішньопартійний трансфер"


def normalize_expense_text(value) -> str:
    """Normalize noisy payment text without trying to infer its meaning."""

    if value is None:
        return ""
    try:
        if bool(pd.isna(value)):
            return ""
    except (TypeError, ValueError):
        pass

    text = unicodedata.normalize("NFKC", str(value)).casefold()
    text = text.translate(str.maketrans({"’": "'", "ʼ": "'", "`": "'", "´": "'"}))
    text = re.sub(r"\*+", " <masked> ", text)
    text = re.sub(r"\b\d{1,2}[./-]\d{1,2}[./-]\d{2,4}\b", " <date> ", text)
    text = re.sub(r"\b(?:№|no)\s*[\w./-]+", " <number> ", text)
    text = re.sub(r"\d+(?:[.,]\d+)?", " <number> ", text)
    return re.sub(r"\s+", " ", text).strip()


