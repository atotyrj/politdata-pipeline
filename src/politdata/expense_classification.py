"""Conservative text classification for analytical party expenses.

The classifier deliberately prefers ``Не класифіковано`` over weak guesses.
Internal party transfers are identified only by the already-enriched receiver
type.  Every other category is derived exclusively from ``payment_purpose``
and ``payment_reason``.
"""

from __future__ import annotations

